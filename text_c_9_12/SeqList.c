// SeqList.c：顺序表所有"函数"的具体实现（真正干活的代码）
// 每个函数都配合注释讲清楚：它想干嘛、为什么这么写。
#include "SeqLsit.h"

// ==================================================================
// SLInit —— 初始化
// 目的：刚定义一个结构体变量时，里面装的是随机的"垃圾值"。
//       如果不初始化就直接用，程序会崩溃或者结果莫名其妙。
//       所以第一步永远是调用这个函数，把三个成员都设成"空"的状态。
// 参数：SL* ps 是"指向顺序表的指针"，因为函数要修改结构体内部数据，
//       必须把地址传进来（值传递的话，函数里改的只是副本，外面没变）。
// ==================================================================
void SLInit(SL* ps)
{
	ps->a = NULL;       // 还没有申请内存，指针先指向空（NULL 就是"什么都没指向"）
	ps->size = 0;       // 有效元素个数 = 0，柜子是空的
	ps->capacity = 0;   // 容量 = 0，一个格子都还没有
}

// ==================================================================
// SLDestroy —— 销毁 / 归还内存
// 目的：之前用 malloc/realloc 向系统"借"的内存，用完之后必须还回去，
//       否则内存一直占着不还，程序长时间运行就会内存泄漏。
//       就像一个同学借了你的书，看完必须还。
// 记住规矩：有借有还（用了内存，结束一定要调用它）。
// ==================================================================
void SLDestroy(SL* ps)
{
	free(ps->a);        // free = 把刚才借的内存放在"还"给系统
	ps->a = NULL;       // 还完之后指针变成"悬空的野指针"，必须立刻置空，防止误用
	ps->size = 0;       // 重置为 0
	ps->capacity = 0;   // 重置为 0
}

// ==================================================================
// SLCheckCapacity —— 检查容量 / 扩容（这个是内部工具函数）
// 目的：每次要往里面塞新元素之前，先问一句"还有空位置吗？"
//        有  → 直接结束，什么都不做。
//        没有 → 申请一块更大的内存，把旧数据全部搬过去，再用新内存。
// 为什么扩容要 x2：因为每搬一次内存都很费时间，一次多扩一点，
//       就能减少搬家的次数，效率更高。这是计算机里的常见做法。
// ==================================================================
void SLCheckCapacity(SL* ps)
{
	// 当"已装的个数" == "柜子总容量"时，说明满了，需要扩容
	if (ps->size == ps->capacity)
	{
		// 第一次进来 capacity 是 0，0 * 2 还是 0，没用。
		// 所以第一次直接给 4 个位置，之后每满一次翻一倍。
		int newCapacity = ps->capacity == 0 ? 4 : ps->capacity * 2;

		// realloc 是"重新申请内存"：
		// 在原内存的基础上扩大到能装 newCapacity 个元素的大小。
		// 如果原来那块的后面还有空地就直接扩大；
		// 如果后面被别的数据占了，它会另找一块更大的空地，
		//    把旧数据原封不动搬过去，然后把旧内存自动释放。
		// 特别注意：结果先存到临时量 tmp 里，不要直接覆盖 ps->a。
		//    因为如果申请失败会返回 NULL，直接赋值会把原来的地址弄丢，数据就没了。
		SLDataType* tmp = (SLDataType*)realloc(ps->a, newCapacity * sizeof(SLDataType));

		if (tmp == NULL)          // 申请失败（比如电脑内存真的不够了）
		{
			printf("扩容失败，无法再插入！\n");
			return;               // 直接返回，别继续往下走了
		}

		ps->a = tmp;              // 扩容成功，把新地址交给我们结构体里的指针
		ps->capacity = newCapacity; // 更新容量这个"柜子一共几格"的记录
	}
}

// ==================================================================
// SLPushBack —— 尾部插入（最常用、最简单的一种"增"）
// 目的：在最后一个有效元素后面，新放一个元素 x。
// 思路：直接把 x 放进"当前最后一个空位"即可，前面的元素完全不用动。
//   例：现在装着 1 2 3（size=3），push back 5 → 1 2 3 5（size=4）
// ==================================================================
void SLPushBack(SL* ps, SLDataType x)
{
	SLCheckCapacity(ps);       // 第一步：确保还有位置（满了会自动扩容）
	ps->a[ps->size] = x;       // 第二步：放进"第 size 号格子"。下标从 0 开始，
	                           //        所以下一个空位下标正好等于 size。
	ps->size++;                // 第三步：装好了，有效个数 +1
}

// ==================================================================
// SLPushFront —— 头部插入（最费力的一种"增"）
// 目的：在第一个位置（下标 0）插入一个新元素。
// 思路：像排队时有人插到最前面，后面所有人必须"整齐地往后让一步"。
//   例：现装 2 3 4，头插 1 → 1 2 3 4
// ==================================================================
void SLPushFront(SL* ps, SLDataType x)
{
	SLCheckCapacity(ps);       // 第一步：确保有位置
	int end = ps->size - 1;    // end = 最后一个有效元素的下标（size-1）
	                           // 从队伍最后那位开始，挨个往后挪
	while (end >= 0)           // 一直挪到下标 0 也挪完为止
	{
		ps->a[end + 1] = ps->a[end]; // 把"当前这位"拷到后面一格（腾出一个空位）
		end--;                       // 往前退一位，继续挪前面的
	}
	ps->a[0] = x;              // 全部挪完之后，下标 0 空出来了，放 x
	ps->size++;                // 有效个数 +1
}

// ==================================================================
// SLInsert —— 在任意位置插入
// 目的：把 x 插到"下标 pos"这个位置，pos 后面的元素全部依次往后挪一格。
//   例：装有 1 2 3 4，往下标 2 插 99 → 1 2 99 3 4
// ==================================================================
void SLInsert(SL* ps, int pos, SLDataType x)
{
	// pos 必须合法：最小是 0（最前面），最大可以等于 size（插到末尾）
	if (pos < 0 || pos > ps->size)
	{
		printf("插入位置非法！\n");
		return;                    // 位置不对就直接返回，别做后面的事
	}

	SLCheckCapacity(ps);           // 确保有位置

	int end = ps->size - 1;        // 从最后一个元素开始挪
	while (end >= pos)             // 只有下标 >= pos 的元素才需要往后让
	{
		ps->a[end + 1] = ps->a[end]; // 往后挪一格
		end--;
	}
	ps->a[pos] = x;                // pos 位置空出来后，把 x 放进去
	ps->size++;                    // 有效个数 +1
}

// ==================================================================
// SLPopBack —— 尾部删除（最简单的一种"删"）
// 目的：删掉最后一个有效元素。
// 思路：根本不用真去把内存清空，只需要让"有效个数 size 减 1"。
//       因为以后所有操作都只看前 size 个格子，最后那个数据虽然还在内存里，
//       但已经没人理它了 = 相当于被删除了。这就是"逻辑删除"。
//   例：装有 1 2 3 4，尾删 → 1 2 3
// ==================================================================
void SLPopBack(SL* ps)
{
	if (ps->size == 0)             // 如果本来就空了，再减会变成负数，就出错了
	{
		printf("顺序表已空，无法删除！\n");
		return;
	}
	ps->size--;                    // 只需要这一行！有效个数 -1
}

// ==================================================================
// SLPopFront —— 头部删除
// 目的：删掉第一个元素（下标 0）。
// 思路：和"头插"相反——把头删掉后，后面每个人都要"往前补一步"，
//       把空出来的位置填上。
//   例：装有 1 2 3 4，头删 → 2 3 4
// ==================================================================
void SLPopFront(SL* ps)
{
	if (ps->size == 0)             // 空表不能删
	{
		printf("顺序表已空，无法删除！\n");
		return;
	}
	int begin = 0;                 // 从下标 0 开始，让后面的往前补
	while (begin < ps->size - 1)   // 一直补到倒数第二个（最后一个不用往前补）
	{
		ps->a[begin] = ps->a[begin + 1]; // 用后一个元素覆盖当前的
		begin++;
	}
	ps->size--;                    // 有效个数 -1
}

// ==================================================================
// SLErase —— 删除任意位置
// 目的：删掉下标 pos 的那个元素，pos 后面的元素全部往前挪一格（补位）。
//   例：装有 1 99 2 3，删下标 1 → 1 2 3
// ==================================================================
void SLErase(SL* ps, int pos)
{
	// 合法的删除位置：0 ~ size-1（注意这里不能等于 size，因为那个位置没有元素）
	if (pos < 0 || pos >= ps->size)
	{
		printf("删除位置非法！\n");
		return;
	}
	int begin = pos + 1;           // 从"被删元素的后一位"开始往前补
	while (begin < ps->size)       // 补到最后一个元素为止
	{
		ps->a[begin - 1] = ps->a[begin]; // 后一个盖住前一个
		begin++;
	}
	ps->size--;                    // 有效个数 -1
}

// ==================================================================
// SLFind —— 查找
// 目的：看看 x 在不在顺序表里，在的话返回它的下标，不在返回 -1。
// 说明：-1 表示"找不到"，因为合法的下标从 0 开始，-1 永远不会冲突。
//   这就像老师点名，喊到"张三"时，他举起手告诉你自己坐在第几排。
// ==================================================================
int SLFind(SL* ps, SLDataType x)
{
	for (int i = 0; i < ps->size; i++) // 从头到尾挨个看
	{
		if (ps->a[i] == x)             // 找到了相等的元素
		{
			return i;                  // 立刻返回它的下标（函数到这里就结束了）
		}
	}
	return -1;                         // 全部看完都没有 → 返回 -1 代表"没找到"
}

// ==================================================================
// SLPrint —— 打印
// 目的：把顺序表里所有有效元素按顺序打印出来，方便观察和调试。
// ==================================================================
void SLPrint(SL* ps)
{
	for (int i = 0; i < ps->size; i++) // 下标 0 到 size-1 就是所有有效元素
	{
		printf("%d ", ps->a[i]);       // 每个元素后面打一个空格，好看
	}
	printf("\n");                      // 全部打完，换一行
}