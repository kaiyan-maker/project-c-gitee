// text.c —— 顺序表的"使用说明书"，也就是演示怎么一步步用它
// 整套顺序表代码分三层，脑子只用记住三层就行：
//   1. 头文件 SeqLsit.h：告诉你"有哪些功能"（像目录/说明书）
//   2. 实现文件 SeqList.c：每个功能"具体怎么做"（像后面的正文）
//   3. 这个文件 text.c：你只管"调用"，不用管内部细节（像用手机，只管点按钮）
//
// 用顺序表永远就四个固定套路，背下来就通了一半：
//   第一步：定义变量      SL s;
//   第二步：初始化        SLInit(&s);
//   第三步：随便增删查打   SLPrint(&s); SLFind(&s, x); ...
//   第四步：用完销毁      SLDestroy(&s);
// ==================================================================

#include "SeqLsit.h"

int main()
{
	// ---------- 第一步：定义 ----------
	// 定义一个叫 s 的顺序表变量。
	// 注意：此时它里面的三个成员都是"垃圾值"，还绝对不能拿来用！
	SL s;

	// ---------- 第二步：初始化 ----------
	// 传 &s（取地址符号）。因为初始化要修改 s 的内容，
	// 必须把 s 的"地址/门牌号"告诉函数，函数才能找到真正的 s 去改。
	SLInit(&s);

	// ---------- 第三步：开始使用（增删查打） ----------
	// [增] 尾插：在末尾依次放入 1 2 3 4
	SLPushBack(&s, 1);
	SLPushBack(&s, 2);
	SLPushBack(&s, 3);
	SLPushBack(&s, 4);
	SLPrint(&s);        // 打印结果：1 2 3 4

	// [增] 头插：在最前面插入 0
	SLPushFront(&s, 0);
	SLPrint(&s);        // 打印结果：0 1 2 3 4

	// [增] 指定位置插入：在下标 2 的位置插入 99
	SLInsert(&s, 2, 99);
	SLPrint(&s);        // 打印结果：0 1 99 2 3 4

	// [删] 尾删：删掉最后一个元素
	SLPopBack(&s);
	SLPrint(&s);        // 打印结果：0 1 99 2 3

	// [删] 头删：删掉第一个元素
	SLPopFront(&s);
	SLPrint(&s);        // 打印结果：1 99 2 3

	// [删] 指定位置删除：删掉下标 1 的元素（也就是 99）
	SLErase(&s, 1);
	SLPrint(&s);        // 打印结果：1 2 3

	// [查] 查找数字 2 在哪个位置
	int pos = SLFind(&s, 2);
	if (pos == -1)
	{
		printf("没有找到 2\n");
	}
	else
	{
		printf("找到了！2 的下标是 %d\n", pos);
	}

	// ---------- 第四步：销毁 ----------
	// 用完了，把之前申请的内存还回去，防止内存泄漏。
	SLDestroy(&s);

	return 0;
}