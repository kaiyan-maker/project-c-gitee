#include<stdio.h>

/*
 * 题目：汽水瓶换汽水问题
 * 已知1瓶汽水1元，2个空瓶可以换1瓶汽水。
 * 输入整数 n（n >= 0），表示 n 元钱，计算一共可以喝多少瓶汽水。
 * 
 * 思路：
 * 1. 用 n 元钱买 n 瓶汽水，喝完后得到 n 个空瓶。
 * 2. 每 2 个空瓶可以换 1 瓶新的汽水，喝完后又产生空瓶。
 * 3. 重复兑换，直到空瓶不足 2 个为止。
 */

int main()
{
	int n = 0;        // 输入的金额（元），即初始能买的汽水瓶数
	int total = 0;    // 总共喝到的汽水数量
	int empty = 0;    // 当前手中持有的空瓶数量

	// 读取用户输入的金额
	scanf_s("%d", &n);

	// 第一步：用 n 元钱买 n 瓶汽水，喝完后获得 n 个空瓶
	total += n;   // 喝了 n 瓶，累计到总数
	empty += n;   // 产生 n 个空瓶

	// 第二步：循环兑换，直到空瓶不足 2 个
	while (empty >= 2)
	{
		// 用空瓶兑换汽水：每 2 个空瓶换 1 瓶
		int newSoda = empty / 2;        // 本次兑换到的汽水瓶数
		int leftover = empty % 2;       // 兑换后剩余的零散空瓶数

		total += newSoda;               // 喝掉新兑换的汽水，总数增加
		empty = newSoda + leftover;     // 喝完后，空瓶数 = 新产生的空瓶 + 剩余零散空瓶
	}

	// 输出最终总共能喝到的汽水数量
	printf("%d\n", total);

	return 0;
}