#define _CRT_SECURE_NO_WARNINGS 1
#include<stdio.h>

/*  求裴波纳契数列  */
/*
 * 斐波那契数列的定义：
 *   第 0 项 F(0) = 0
 *   第 1 项 F(1) = 1
 *   第 n 项 F(n) = F(n-1) + F(n-2)   (n >= 2)
 * 展开看就是从 0, 1 开始，后面每一项都等于前两项之和：
 *   0, 1, 1, 2, 3, 5, 8, 13, 21 ...
 *
 * 递归思路：
 *   想求 F(n)，把它拆成两个更小的问题 F(n-1) 和 F(n-2)，
 *   这两个又会接着往下拆，直到拆到 F(0) 或 F(1)，
 *   这两个是"已知答案"的终止条件，返回 0 或 1 后原路加回来。
 *   原理同样符合递归两要素：终止条件 + 递推公式。
 */
int Frb(int n)
{
	if (n == 0)
		return 0;   // 终止条件 1：第 0 项的值就是 0，直接返回，不再递归
	if (n == 1)
		return 1;   // 终止条件 2：第 1 项的值就是 1
	if (n >= 2)
		/*
		 * 递推公式：F(n) = F(n-1) + F(n-2)，两项一起往下递归。
		 *
		 * 【重要陷阱，复习必看】
		 * 这里第二项写的是 F(n+1)，是个 bug：
		 *     F(n+1) 会继续拆成 F(n+2)、F(n+3)……参数越来越大，
		 *     永远到不了 0 或 1 这两个终止条件，
		 *     于是递归无限进行，把栈耗尽导致程序崩溃，打印永远不出现。
		 * 正确写法应为 Frb(n - 2)，这样参数一路递减，早晚落到终止条件。
		 */
		return Frb(n - 1) + Frb(n - 2);
}

int main()
{
	int n = 0;
	// 输入想求第几项，下面算 F(n)
	// scanf("%d", &n)：把键盘输入写到 n 的地址，& 不能丢

	int p = Frb(n);  // 交递归函数计算，得到的就是第 n 项的值

	printf("%d", p);  // 打印 F(n)
	return 0;
}