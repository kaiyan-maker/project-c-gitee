#define _CRT_SECURE_NO_WARNINGS 1
#include<stdio.h>

/*  求100 的阶乘  */
/*
 * 思路：
 * n! 的定义：n! = n × (n-1) × (n-2) × ... × 1，另外规定 0! = 1。
 * 递归的写法靠一个等价关系：n! = n × (n-1)!。
 *   想算 n!，就把它拆成 "n × 小一号问题的答案(n-1)!"，
 *   算 (n-1)! 又拆成 (n-1) × (n-2)!...
 *   一路拆到 0!，0! 直接知道等于 1，就不再往下拆，开始原路乘回来。
 * 这就是"递归的两个要素"：
 *   1. 终止条件（base case）：什么时候不用再拆了；
 *   2. 递推公式：把大问题转化成规模更小的问题。
 *
 * 补充说明：
 *   - 文件注释写的是"100 的阶乘"，但代码实际上是由用户输入 n、
 *     计算 n! 的通用程序，两者核对一下，复习时别被标题误导。
 *   - int 最大只能存约 21 亿，12! 就已经接近上限，
 *     所以 n 超过 12 左右结果就会溢出，得到乱码。
 *     要算 100! 必须用数组/大数方法，int 根本装不下。
 */
int Frb(int n)
{
	if (n == 0)
		return 1;  // 终止条件：0! = 1，拆到这一步就直接返回，不再递归
	return n * Frb(n - 1);  // 递推公式：n! = n × (n-1)!，问题规模每次减 1
}

int main()
{
	int n = 0;
	// 输入一个数 n，下面算 n!
	// scanf("%d", &n)：把键盘输入写到 n 的地址，& 不能丢

	int p = Frb(n);  // 把 n 交给递归函数，等它把结果一层层乘回来

	printf("%d", p);  // 打印结果（就是 n!）
	return 0;
}